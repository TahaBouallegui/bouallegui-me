// Build feed.xml from the published posts.
//
// The posts themselves are the source of truth: each one carries its title in the
// h1, its summary in the description meta, its date in <time datetime>, and its
// body in <article>. Nothing here duplicates that metadata, so the feed cannot
// drift from the page it points at.
//
// Relative references inside an article are rewritten to absolute ones, because a
// reader application has no directory to resolve "../images/..." against.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SITE = "https://bouallegui.pages.dev";
const POSTS_DIR = "posts";
const OUT = "feed.xml";

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const DAYS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];

// RFC 822 at noon UTC: the post dates are calendar dates, not instants, and noon
// keeps the day the same in every timezone a reader might live in.
function rfc822(iso) {
  const [y, m, d] = iso.split("-").map(Number);
  const utc = new Date(Date.UTC(y, m - 1, d, 12, 0, 0));
  const p = (n) => String(n).padStart(2, "0");
  return `${DAYS[utc.getUTCDay()]}, ${p(d)} ${MONTHS[m - 1]} ${y} 12:00:00 GMT`;
}

function esc(s) {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

// CDATA cannot contain "]]>", so split the body if it ever does.
function cdata(s) {
  return "<![CDATA[" + s.replace(/\]\]>/g, "]]]]><![CDATA[>") + "]]>";
}

function absolutize(html) {
  return html.replace(/(src|href|poster)="([^"]*)"/g, (all, attr, url) => {
    if (/^(https?:|mailto:|tel:|#|data:)/.test(url)) return all;
    const abs = url.startsWith("../") ? `${SITE}/${url.slice(3)}` : `${SITE}/${POSTS_DIR}/${url}`;
    return `${attr}="${abs}"`;
  });
}

function parsePost(file) {
  const html = readFileSync(join(POSTS_DIR, file), "utf8");
  const pick = (re, what) => {
    const m = html.match(re);
    if (!m) throw new Error(`${file}: no ${what}`);
    return m[1].trim();
  };
  return {
    file,
    title: pick(/<h1 class="section-title[^"]*">([\s\S]*?)<\/h1>/, "h1"),
    desc: pick(/<meta name="description" content="([^"]*)"/, "description"),
    date: pick(/<time datetime="(\d{4}-\d{2}-\d{2})"/, "date"),
    body: pick(/<article[^>]*>([\s\S]*?)<\/article>/, "article"),
  };
}

const posts = readdirSync(POSTS_DIR)
  .filter((f) => f.endsWith(".html"))
  .map(parsePost)
  .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.file < b.file ? -1 : 1));

const build = rfc822(posts[0].date);

const items = posts
  .map(
    (p) => `    <item>
      <title>${esc(p.title)}</title>
      <link>${SITE}/${POSTS_DIR}/${p.file}</link>
      <guid isPermaLink="true">${SITE}/${POSTS_DIR}/${p.file}</guid>
      <pubDate>${rfc822(p.date)}</pubDate>
      <description>${esc(p.desc)}</description>
      <content:encoded>${cdata(absolutize(p.body))}</content:encoded>
    </item>`,
  )
  .join("\n");

const feed = `<?xml version="1.0" encoding="UTF-8"?>
<!-- SPDX-FileCopyrightText: 2026 Ahmed Taha Bouallegui -->
<!-- SPDX-License-Identifier: GPL-3.0-or-later -->
<!-- Generated by scripts/build-feed.mjs from posts/*.html. Edit the posts, not this file. -->
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:content="http://purl.org/rss/1.0/modules/content/">
  <channel>
    <title>Ahmed Bouallegui: field notes</title>
    <link>${SITE}/blog.html</link>
    <description>Notes from the lab and from my own machines: a NixOS config shared by three machines, wireless detection over nl80211, self-hosted services, and running models locally.</description>
    <language>en</language>
    <copyright>Copyright 2026 Ahmed Taha Bouallegui, GPL-3.0-or-later</copyright>
    <lastBuildDate>${build}</lastBuildDate>
    <generator>scripts/build-feed.mjs</generator>
    <atom:link href="${SITE}/feed.xml" rel="self" type="application/rss+xml"/>
    <image>
      <url>${SITE}/images/feed.png</url>
      <title>Ahmed Bouallegui: field notes</title>
      <link>${SITE}/blog.html</link>
      <width>144</width>
      <height>144</height>
    </image>
${items}
  </channel>
</rss>
`;

writeFileSync(OUT, feed);
console.log(`${OUT}: ${posts.length} items, newest ${posts[0].date} (${posts[0].file}), ${(feed.length / 1024).toFixed(1)} KB`);
